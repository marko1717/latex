def КП8_має(a, кінці=False, знак=1):
    """корінь чисельника log_3(x + a) = 2 має задовольнити ОДЗ: x + a > 0 і (x - a)(20 - x) > 0"""
    for r in дійсні(solve(log(x + знак * a, 3) - 2, x)):
        d = (r - a) * (20 - r)
        if r + знак * a > 0 and (d > 0 or (кінці and d == 0)): return True
    return False
