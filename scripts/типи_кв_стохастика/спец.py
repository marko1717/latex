def розв(рівняння):
    """єдиний додатний розв'язок лінійного рівняння відносно n"""
    r = solve(рівняння, n_)
    assert len(r) == 1, r
    return r[0]


def стовпчики(дані, крок, підпис_y, висота=3.6, ширина=0.95):
    """стовпчикова діаграма як у НМТ: горизонтальні лінії сітки з поділками на осі, стовпчики, підписи під ними"""
    верх = math.ceil(max(v for _, v in дані) / крок) * крок
    k = висота / верх
    s = [r"\begin{tikzpicture}[x=%.2fcm, y=%.5fcm]" % (ширина, k)]
    for v in range(0, верх + крок, крок):
        s.append(r"\draw[gray!45, very thin] (0,%d) -- (%.2f,%d); \node[left, font=\scriptsize] at (0,%d) {$%d$};" % (v, len(дані) + 0.4, v, v, v))
    s.append(r"\draw[->] (0,0) -- (0,%.3f) node[above, font=\scriptsize] {%s};" % (верх + 0.28 / k, підпис_y))
    s.append(r"\draw (0,0) -- (%.2f,0);" % (len(дані) + 0.4))
    for i, (назва, v) in enumerate(дані):
        s.append(r"\filldraw[fill=mainGreen!40, draw=mainGreen!70!black] (%.2f,0) rectangle (%.2f,%s);" % (i + 0.65, i + 1.35, v))
        s.append(r"\node[below, font=\scriptsize] at (%.2f,0) {%s};" % (i + 1, назва))
    s.append(r"\end{tikzpicture}")
    return "\n".join(s)


def кругова(сектори, R_=2.0):
    """кругова діаграма: [(назва, частка від 0 до 1, підпис частки або None -- тоді підписано кут сектора)];
    підписи широких секторів -- усередині, вузьких (менше $80^\circ$) -- назовні, щоб не налазили на межі"""
    s = [r"\begin{tikzpicture}"]
    кольори = ["mainGreen!45", "cyan!30", "yellow!45", "orange!40", "violet!25"]
    a = 90.0
    for (назва, частка, підпис), колір in zip(сектори, кольори):
        b = a - 360 * float(частка)
        s.append(r"\filldraw[fill=%s, draw=black!70] (0,0) -- (%.2f:%.2f) arc[start angle=%.2f, end angle=%.2f, radius=%.2f] -- cycle;" % (колір, a, R_, a, b, R_))
        m = (a + b) / 2
        бік = "west" if math.cos(math.radians(m)) > 0 else "east"
        текст = "%s, %s" % (назва, підпис) if підпис else назва
        if not підпис:
            s.append(r"\draw (%.2f:0.45) arc[start angle=%.2f, end angle=%.2f, radius=0.45];" % (a, a, b))
            s.append(r"\node[font=\scriptsize] at (%.2f:0.75) {$%d^\circ$};" % (m, round(360 * float(частка))))
        if підпис and a - b >= 80:
            s.append(r"\node[font=\scriptsize, align=center] at (%.2f:%.2f) {%s\\%s};" % (m, R_ * 0.6, назва, підпис))
        else:
            s.append(r"\node[font=\scriptsize, anchor=%s] at (%.2f:%.2f) {%s};" % (бік, m, R_ + 0.1, текст))
        a = b
    s.append(r"\end{tikzpicture}")
    return "\n".join(s)


def таблиця(рядки, ширина_першого="3.4cm"):
    """таблиця даних як у НМТ 2026: перший стовпчик -- назви рядків"""
    k = len(рядки[0]) - 1
    s = [r"\renewcommand{\arraystretch}{1.3}\begin{tabular}{|>{\raggedright\arraybackslash}m{%s}|*{%d}{c|}}\hline" % (ширина_першого, k)]
    for r in рядки:
        s.append(r"\textbf{%s} & " % r[0] + " & ".join(r[1:]) + r" \\ \hline")
    s.append(r"\end{tabular}")
    return "\n".join(s)


