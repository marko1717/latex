def нфк(s): return unicodedata.normalize("NFC", s)


def _норм(x):
    return re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ]+", "", re.sub(r"\\(?:textit|mbox|text|dfrac|frac|sqrt|par|quad)\b|\^\\circ|°", "", x))


def _пункти(b, мітки):
    return [(l, _норм(x)) for l, x in re.findall(r"\\matchItem\{([^{}]*)\}\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", b) if l in мітки]


def той_самий(b1, b2):
    """одне завдання в різному оформленні: ті самі п'ять варіантів А--Д і схожі пункти 1--3
    («висота з вершини B» / «висота, проведена з вершини B»); однакові варіанти мають і різні завдання"""
    o1, o2 = _пункти(b1, "АБВГД"), _пункти(b2, "АБВГД")
    if len(o1) != 5 or o1 != o2: return False
    i1, i2 = "".join(x for _, x in _пункти(b1, "123")), "".join(x for _, x in _пункти(b2, "123"))
    return difflib.SequenceMatcher(None, i1, i2).ratio() >= 0.6


ПРОДОВЖЕННЯ = re.compile(r"(\\matchItem\{[^{}]*\}\{(?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}(?:\s*\\nmtnobreak)?[ \t]*\n\s*\\quad\\quad[ \t]*([^\n\\][^\n]*?)[ \t]*\n")


def зшити_пункти(b):
    """у частині завдань бази довгий пункт розбито: «\\matchItem{1}{Відстань від точки $K$ до}» і окремим рядком
    «\\quad\\quad середини сторони $BC$» -- продовження стоїть поза пунктом і налазить на наступний.
    Вклеюємо продовження в сам пункт: він переноситься в межах своєї колонки."""
    while True:
        b2 = ПРОДОВЖЕННЯ.sub(lambda m: m.group(1) + " " + m.group(2) + "}\n", b)
        if b2 == b: return b
        b = b2


def пита_площу(b):
    """запобіжник: заголовок колонки чи пункт про площу (не «площина»)"""
    шматки = re.findall(r"\\matchHead\{([^{}]*)\}", b) + [x for l, x in re.findall(
        r"\\matchItem\{([1-3])\}\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", b)]
    умова = re.split(r"\\matchingLayout", b)[0]
    return any(re.search(r"[Пп]лощ(?!ин)", x) for x in шматки) or bool(re.search(r"(фігур\w*|трикутник\w*)[^.]{0,40}(з|та)\s+її\s+площ", умова))


def аналоги_площі():
    ген = {g["id"]: g for g in json.load(open(os.path.join(HERE, "data", "варіант_згенеровані.json"), encoding="utf-8"))}
    кат = {t["код"]: t for t in json.load(open(os.path.join(HERE, "data", "типи_відп_планіметрія_нмт.json"), encoding="utf-8"))}
    out = []
    for джерело, i in АНАЛОГИ_ПЛОЩІ:
        z = ген[i] if джерело == "ген" else кат[i]
        b, відп = z["latex"], z["відповідь"]
        assert джерело != "ген" or z.get("перевірено"), ("аналог не перевірено", i)
        assert пита_площу(b), ("аналог не про площі", i)
        assert len(відп) == 3 and len(set(відп)) == 3 and set(відп) <= set(L), (i, відп)
        out.append(dict(id=i, тип=(z.get("тип_каталогу") or i), блок=b, відповідь=відп))
    return out


def main(площі=False):
    класи = json.load(open(os.path.join(HERE, "data", "типи_класифікація.json"), encoding="utf-8"))
    каталог = {c["id"]: c for c in json.load(open(os.path.join(HERE, "data", "варіант_каталог.json"), encoding="utf-8"))}
    блоки = {t["id"]: t for t in SP.завдання_бази()}
    ids = [i for i, тип in класи.items() if тип.startswith("відп_планіметрія:")]
    взято, повтори, відкинуто = [], collections.Counter(), collections.Counter()
    бачені = {}           # id -> блок узятих завдань
    for i in sorted(ids, key=lambda i: (каталог[i]["рік"], i)):
        if (i in ПЛОЩІ) != площі: відкинуто["без площ" if площі else "площі"] += 1; continue
        if i in ВАДИ: відкинуто["вади"] += 1; continue
        b = блоки[i]["блок"]
        assert пита_площу(b) == площі, ("завдання про площу не в таблиці ПЛОЩІ" if not площі else "у таблиці ПЛОЩІ, а площу не питає", i)
        if i in ЯВНІ_ПОВТОРИ: повтори[ЯВНІ_ПОВТОРИ[i]] += 1; continue
        двійник = next((j for j, bj in бачені.items() if той_самий(bj, b)), None)
        if двійник: повтори[двійник] += 1; continue
        бачені[i] = b
        відп = каталог[i].get("відповідь")
        assert відп and len(відп) == 3 and len(set(відп)) == 3 and set(відп) <= set(L), ("немає коректної відповіді", i, відп)
        взято.append(dict(id=i, тип=класи[i].split(":")[1], рік=каталог[i]["рік"], блок=b, відповідь=відп, файл=блоки[i]["файл"]))

    # преамбула і макроси -- як у тематичних збірниках (з теми «Трикутники»)
    назва_збірника, файл = (НАЗВА_ПЛОЩІ, ФАЙЛ_ПЛОЩІ) if площі else (НАЗВА, ФАЙЛ)
    ZT.CFG = dict(src=[("", "11. Трикутники/завдання.tex")], title=назва_збірника)
    pre = ZT.preamble()
    теки = sorted({нфк(os.path.dirname(z["файл"])) + "/" for z in взято})
    pre = re.sub(r"\\graphicspath\{.*\}\s*\n", "", pre) + "\\graphicspath{{./}%s}\n" % "".join("{%s}" % t for t in теки)
    out = [pre, "\\begin{document}\n" + ZT.carried_macros() + "\n\\setcounter{zad}{0}\n", "\\chapterTitle{%s}\n" % назва_збірника, ""]
    анот = len(out) - 1
    порядок = []
    for назва, типи in ГРУПИ:
        гр = sorted([z for z in взято if z["тип"] in типи], key=lambda z: (z["рік"], z["id"]))
        if not гр: continue
        if not площі: out.append("\\typeTitle{%s}\n" % назва)
        for k, z in enumerate(гр):
            заголовок = "\\needspace{0.45\\textheight}\\typeTitle{%s}\n" % назва if площі and k == 0 else ""   # не відривати від першого завдання
            out.append("\\begin{samepage}\n%s%s\n\\end{samepage}\n" % (заголовок, зшити_пункти(z["блок"]).strip()))
            порядок.append(z)
    assert len(порядок) == len(взято), "є типи поза групами"
    роки = collections.Counter(z["рік"] for z in порядок)
    аналоги = аналоги_площі() if площі else []
    if аналоги:
        for k, z in enumerate(аналоги):
            заголовок = "\\needspace{0.45\\textheight}\\typeTitle{Авторські аналоги за зразком НМТ}\n" if k == 0 else ""
            out.append("\\begin{samepage}\n%s%s\n\\end{samepage}\n" % (заголовок, зшити_пункти(z["блок"]).strip()))
    if площі:
        out[анот] = ("\\noindent{\\small Збірник містить \\textbf{%d справжніх завдань} НМТ %s--%s років на встановлення відповідності "
                     "з планіметрії, у яких \\textit{треба знайти площу}: трикутників, частин прямокутника, паралелограма, трапеції, "
                     "фігур між паралельними прямими й на папері в клітинку. Таких завдань у НМТ 2023--2026 небагато, тому наприкінці "
                     "додано \\textbf{%d авторські аналоги} за зразком НМТ. Завдання згруповано за фігурою; біля кожного оригіналу "
                     "вказано рік. Відповіді~--- на останній сторінці. Завдання на відповідність без площ~--- в окремому збірнику "
                     "«Геометрія: завдання на відповідність без обчислення площ».\\par\\vspace{0.15cm}\n"
                     "За роками: %s.}\\par\\vspace{0.45cm}\n") % (
                         len(порядок), min(роки), max(роки), len(аналоги),
                         ", ".join("\\mbox{%s~--- %d}" % (р, n) for р, n in sorted(роки.items())))
    else:
        out[анот] = ("\\noindent{\\small Збірник містить \\textbf{%d завдань} НМТ %s--%s років на встановлення відповідності з планіметрії, "
                 "у яких \\textit{не треба знаходити площу}: довжини відрізків, кути, радіуси кіл, периметри. Завдання зібрано з бази НМТ "
                 "і згруповано за фігурою; біля кожного вказано рік. Відповіді~--- на останній сторінці.\\par\\vspace{0.15cm}\n"
                 "За роками: %s.}\\par\\vspace{0.45cm}\n") % (
                     len(порядок), min(роки), max(роки), ", ".join("\\mbox{%s~--- %d}" % (р, n) for р, n in sorted(роки.items())))
    out.append("\\clearpage\n\\sectionTitle{Відповіді}\n")
    out.append("\\noindent{\\small\\color{gray!80!black}Для кожного завдання -- літери відповідей для пунктів 1, 2, 3. "
               "Відповіді обчислено й звірено з офіційними ключами там, де вони є.}\\par\\vspace{0.3cm}\n")
    out.append("\\begin{multicols}{5}\\noindent\n" + "\\par\n".join("\\mbox{%d~--- %s}" % (n, z["відповідь"]) for n, z in enumerate(порядок + аналоги, 1))
               + "\n\\end{multicols}\n")
    if аналоги:
        out.append("\\noindent{\\small\\color{gray!80!black}%d--%d~--- авторські аналоги.}\\par\n" % (len(порядок) + 1, len(порядок) + len(аналоги)))
    out.append("\\end{document}\n")
    open(os.path.join(ROOT, файл), "w", encoding="utf-8").write(нфк("\n".join(out)))
    stem = файл[:-4]
    чистий = нфк(stem + "_без_водяного_знака.tex")
    open(os.path.join(ROOT, чистий), "w", encoding="utf-8").write(нфк(
        "%% Збірник «%s» без водяного знака @pvtr2525 -- версія для вчителів.\n"
        "%% Компілюйте цей файл (XeLaTeX); завдання беруться з %s.tex.\n"
        "\\def\\nmtnowatermark{}\n\\input{%s}\n" % (назва_збірника, stem, stem)))
    print("записано", файл, "і", чистий)
    print("   оригіналів-відповідностей з планіметрії: %d; узято %d (+ аналогів %d); відкинуто %s, повторів %d" % (
        len(ids), len(порядок), len(аналоги), dict(відкинуто), sum(повтори.values())))
    print("   за роками:", dict(sorted(роки.items())), "| за групами:",
          [(н, sum(1 for z in порядок if z["тип"] in т)) for н, т in ГРУПИ])


