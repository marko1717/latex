def д(P, Q):
    return sqrt((P[0] - Q[0]) ** 2 + (P[1] - Q[1]) ** 2)


def площа(*pts):
    """площа многокутника за координатами вершин (формула шнурування)"""
    n = len(pts)
    return Abs(sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n))) / 2


def кут(A, O, B):
    """градусна міра кута AOB"""
    u, v = (A[0] - O[0], A[1] - O[1]), (B[0] - O[0], B[1] - O[1])
    return acos((u[0] * v[0] + u[1] * v[1]) / (sqrt(u[0] ** 2 + u[1] ** 2) * sqrt(v[0] ** 2 + v[1] ** 2))) * 180 / pi


def периметр(*pts):
    return sum(д(pts[i], pts[(i + 1) % len(pts)]) for i in range(len(pts)))


def ч(p):
    """координати для рисунка"""
    return (float(p[0]), float(p[1]))


def см(*xs): return [r"$%s$~см" % x for x in xs]
def см2(*xs): return [r"$%s$~см$^2$" % x for x in xs]
def гр(*xs): return [r"$%s^\circ$" % x for x in xs]


