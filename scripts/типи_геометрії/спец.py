def V3(p): return Matrix(p)


def площина(*назви, т):
    p, q, r = (V3(т[n]) for n in назви)
    return (q - p).cross(r - p), p


def паралельна_площині(a, b, пл, т):
    n, p0 = пл
    d = V3(т[b]) - V3(т[a])
    return d.dot(n) == 0 and (V3(т[a]) - p0).dot(n) != 0


def лежить_у_площині(a, b, пл, т):
    n, p0 = пл
    return (V3(т[a]) - p0).dot(n) == 0 and (V3(т[b]) - p0).dot(n) == 0


def мимобіжні(l1, l2, т):
    (a, b), (c, d) = l1, l2
    u, w = V3(т[b]) - V3(т[a]), V3(т[d]) - V3(т[c])
    return u.cross(w) != Matrix([0, 0, 0]) and (V3(т[c]) - V3(т[a])).dot(u.cross(w)) != 0


