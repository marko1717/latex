def pol(r, кут, центр=(0, 0)):
    return (центр[0] + r * math.cos(math.radians(кут)), центр[1] + r * math.sin(math.radians(кут)))


def град(q):
    return r"$%s^\circ$" % q


def рад(g):
    return g * pi / 180


def варіанти_тверджень(набори):
    """набори номерів правильних тверджень -> (показ, варіанти)"""
    показ = []
    for s in набори:
        k = sorted(s)
        показ.append("I, II та III" if len(k) == 3 else "лише %s та %s" % (РИМ[k[0] - 1], РИМ[k[1] - 1]) if len(k) == 2
                     else "лише %s" % РИМ[k[0] - 1] if k else "жодне")
    return показ, [frozenset(s) for s in набори]


def умова_тверджень(вступ, тексти):
    рядки = " \\\\\n".join(r"%s. & %s" % (РИМ[i], т) for i, т in enumerate(тексти))
    return (вступ + "\n" + r"\par\nopagebreak\vspace{0.1cm}\noindent\begin{tabular}{@{}r@{\ \ }p{0.9\linewidth}@{}}" + "\n"
            + рядки + "\n" + r"\end{tabular}")


def правда(*значення):
    """номери правильних тверджень за списком їхніх значень істинності"""
    return frozenset(i + 1 for i, q in enumerate(значення) if q)


