def при(вираз, значення):
    return simplify(sympify(вираз).subs(x, значення))


def вид(v):
    """вид числа, як у правій колонці НМТ"""
    v = simplify(expand_log(sympify(v), force=True))
    if v.is_integer: return "натуральне" if v > 0 else "нуль" if v == 0 else "ціле від'ємне"
    if v.is_rational: return "раціональне неціле"
    if v.is_irrational: return "ірраціональне додатне" if v > 0 else "ірраціональне від'ємне"
    raise ValueError(v)


def пр(ліво, право, ліва_закрита=True, права_закрита=False):
    return Interval(ліво, право, not ліва_закрита, not права_закрита)


def пр_tex(w):
    """проміжок у записі НМТ: $[-2; -1)$"""
    def к(v): return r"-\infty" if v == -oo else r"+\infty" if v == oo else str(v)
    return "$%s%s; %s%s$" % ("(" if w.left_open else "[", к(w.start), к(w.end), ")" if w.right_open else "]")


