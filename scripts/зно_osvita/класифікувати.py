def одиниця(r):
    текст = " ".join([r.get("умова", "")] + r.get("варіанти", []) + r.get("пункти", []))
    for u, pat in ПРАВИЛА:
        if re.search(pat, текст, re.I | re.S): return u
    return "1"


def норм(s):
    s = unicodedata.normalize("NFC", s.lower())
    s = re.sub(r"\\[a-z]+|\[рисунок[^\]]*\]", " ", s)
    return re.sub(r"[^a-zа-яіїєґ0-9]+", "", s)


def main():
    tasks = json.load(open(ЗАВДАННЯ, encoding="utf-8"))
    # збіг із базою: спільні 8-символьні фрагменти (індекс) -> найкращий кандидат -> схожість тексту
    база = {t["id"]: норм(re.sub(r"(?<!\\)%[^\n]*", "", t["блок"]))[:400] for t in S.завдання_бази()}
    індекс = collections.defaultdict(set)
    for i, n in база.items():
        for k in range(0, max(1, len(n) - 8), 4): індекс[n[k:k + 8]].add(i)
    for r in tasks:
        u = одиниця(r)
        тип = "input" if r["тип"] in ("input", "input2") else r["тип"]
        r["теми"] = [u]
        r["родини"] = sorted({S.РОДИНИ[u]} if u in S.РОДИНИ else set())
        r["орієнтовна_категорія"] = rule_category(dict(теми=[u], тип=тип, блок=r.get("умова", ""))) if тип in ("single", "matching", "input") else "відкрите"
        n = норм(r.get("умова", ""))[:400]
        голоси = collections.Counter(i for k in range(0, max(1, len(n) - 8), 2) for i in індекс.get(n[k:k + 8], ()))
        best = None
        for i, _ in голоси.most_common(5):
            bn = база[i]
            q = difflib.SequenceMatcher(None, n, bn[:len(n) + 40], autojunk=False).ratio()
            if q > 0.8 and (not best or q > best[1]): best = (i, q)
        r["є_в_базі"] = best[0] if best and len(n) >= 25 else None
    json.dump(tasks, open(ЗАВДАННЯ, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    нові = [r for r in tasks if not r["є_в_базі"]]
    print("завдань: %d; уже є в базі НМТ: %d; нових: %d" % (len(tasks), len(tasks) - len(нові), len(нові)))
    print("збіги з базою за іспитами:", dict(collections.Counter(r["іспит"] + " " + r["рік"] for r in tasks if r["є_в_базі"])))
    cats = collections.Counter(r["орієнтовна_категорія"] for r in нові)
    print("нові завдання за орієнтовними категоріями слотів:")
    for c in S.СТРУКТУРА_2026:
        if c in cats: print("   %-28s %4d" % (c, cats.pop(c)))
    for c, n in cats.most_common(): print("   %-28s %4d" % (c, n))


if __name__ == "__main__":
    main()
