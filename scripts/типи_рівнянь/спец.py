def eq_set(expr):                  # множина дійсних коренів рівняння expr = 0
    return solveset(expr, x, S.Reals)


def ineq_set(*rels):               # розв'язок нерівності чи системи як множина
    r = reduce_inequalities(list(rels), x)
    return r.as_set()


