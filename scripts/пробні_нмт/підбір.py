"""Підбір типів завдань для пробного НМТ за базою (scripts/data/пробні_база.json): для кожного з 22 слотів -- тип
із ймовірністю, пропорційною тому, як часто він траплявся на НМТ (2026 важить найбільше), лише з тем, які учні вже
пройшли (заборонені теми й типи -- з конфігурації), і так, щоб родина тем (прогресія, логарифми, призма ...)
не повторювалася, крім функцій. Результат -- план: слот, тип, назва, частоти, скільки вже є готових невикористаних
завдань цього типу в базі. Самі завдання пишуться за планом у пробні/<пробний>/спец.py.

    python3 scripts/пробні_нмт/підбір.py --заборонені-теми 34 40 41 42 --seed 1
"""
import os, sys, json, random, argparse, collections
HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(SCRIPTS, "варіант_нмт")); sys.path.insert(0, HERE)
from спільне import СТРУКТУРА_2026, РОДИНИ, МОЖНА_ПОВТОРЮВАТИ   # noqa: E402
from база import ВИХІД as БАЗА                                  # noqa: E402

ВАГА_РОКУ = {"2026": 4.0, "2025": 1.5, "2024": 0.8, "2023": 0.4}


def основні_теми(t, частка=0.34):
    """теми, що трапляються щонайменше в третині оригіналів типу -- за ними тип «належить» родині"""
    n = max(t["оригіналів"], 1)
    return [u for u, c in t["теми"].items() if c / n >= частка]


def вага(t, слот):
    """частоти саме в цьому слоті (типи рівнянь спільні для слотів «рівняння» і «рівняння_трансц»)"""
    return sum(ВАГА_РОКУ.get(р, 0) * n for р, n in t["за_слотами"].get(слот, {}).items())


def план(база, заборонені_теми=(), заборонені_типи=(), обовʼязкові=None, seed=0, спроб=500):
    типи = база["типи"]
    rnd = random.Random(seed)
    обовʼязкові = обовʼязкові or {}
    кандидати = {}
    for s in СТРУКТУРА_2026:
        ks = [k for k, t in типи.items() if s in t["слоти"] and k not in заборонені_типи and вага(t, s) > 0
              and not set(основні_теми(t)) & set(заборонені_теми)]
        if s in обовʼязкові: ks = [k for k in ks if k in обовʼязкові[s]]
        кандидати[s] = ks
    порядок = sorted(СТРУКТУРА_2026, key=lambda s: len(кандидати[s]))
    for _ in range(спроб):
        вибір, родини = {}, set()
        for s in порядок:
            ks = [k for k in кандидати[s] if not ({РОДИНИ[u] for u in основні_теми(типи[k]) if u in РОДИНИ} - МОЖНА_ПОВТОРЮВАТИ) & родини]
            if not ks: break
            k = rnd.choices(ks, weights=[вага(типи[k], s) for k in ks])[0]
            вибір[s] = k
            родини |= {РОДИНИ[u] for u in основні_теми(типи[k]) if u in РОДИНИ} - МОЖНА_ПОВТОРЮВАТИ
        else:
            return [(s, вибір[s]) for s in СТРУКТУРА_2026], кандидати
    raise SystemExit("не вдалося скласти план без повторів родин")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--заборонені-теми", nargs="*", default=[])
    ap.add_argument("--заборонені-типи", nargs="*", default=[])
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    база = json.load(open(БАЗА, encoding="utf-8"))
    вільні = collections.Counter(z["тип"] for z in база["завдання"] if z["джерело"] != "оригінал" and z["придатне"] and not z["використано"])
    p, кандидати = план(база, a.заборонені_теми, a.заборонені_типи, seed=a.seed)
    for i, (s, k) in enumerate(p, 1):
        t = база["типи"][k]
        print("%2d %-26s %-22s %-55s %s | теми %s | кандидатів %d" % (i, s, k, t["назва"][:55], t["за_слотами"].get(s), основні_теми(t), len(кандидати[s])))
