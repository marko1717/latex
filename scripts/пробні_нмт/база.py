# -*- coding: utf-8 -*-
"""База для пробних НМТ: усі завдання, з яких можна складати пробні, з типом за каталогами типів (scripts/типи_*),
темами бази (1--43) і позначкою, де завдання вже використано.

Джерела:
  * оригінали НМТ 2023--2026 -- scripts/data/варіант_каталог.json (перевірені відповіді, дефекти) + тип із
    scripts/data/типи_класифікація.json (класифікація двома незалежними агентами й арбітром);
  * аналоги -- scripts/data/варіант_згенеровані.json (тип успадковано від завдання-зразка);
  * зразки каталогів типів -- scripts/data/типи_*_нмт.json (по одному новому завданню на тип);
  * авторські завдання пробних -- пробні/<пробний>/завдання.json.

    python3 scripts/пробні_нмт/база.py            # зібрати scripts/data/пробні_база.json і надрукувати підсумок

Тип завдання -- ключ «каталог:код», наприклад «алгебра:Д3», «кв_стерео:КС14» (коди В1..В9 є і в рівняннях, і в
геометрії, тому каталог у ключі обов'язковий). Для кожного типу рахуються частоти за роками серед оригіналів --
з них підбір.py бере ваги (як часто тип трапляється на НМТ, передусім 2026)."""
import os, sys, json, glob, collections
HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.dirname(HERE)
ROOT = os.path.dirname(SCRIPTS)
DATA = os.path.join(SCRIPTS, "data")
sys.path.insert(0, os.path.join(SCRIPTS, "варіант_нмт"))
ВИХІД = os.path.join(DATA, "пробні_база.json")

КАТАЛОГИ = {"алгебра": "типи_алгебри", "геометрія": "типи_геометрії", "рівняння": "типи_рівнянь", "відп_вирази": "типи_відп_вирази",
            "відп_функції": "типи_відп_функції", "відп_планіметрія": "типи_відп_планіметрія", "кв_стохастика": "типи_кв_стохастика",
            "кв_функціональне": "типи_кв_функціональне", "кв_стерео": "типи_кв_стерео", "кв_параметр": "типи_кв_параметр"}
# слот варіанта (категорія генератора) -> групи каталогів, з яких він складається
СЛОТИ = {"арифметика": [("алгебра", "Числа")], "статистика": [("алгебра", "Статистика")], "планіметрія_проста": [("геометрія", "Кути")],
         "нерівність": [("рівняння", "Нерівності"), ("рівняння", "Системи нерівностей")], "стерео_тест": [("геометрія", "Стереометрія")],
         "вирази": [("алгебра", "Вирази")], "рівняння_трансц": [("рівняння", "Рівняння"), ("рівняння", "Системи рівнянь")],
         "функція": [("алгебра", "Функції")], "планіметрія_твердження": [("геометрія", "«Які")],
         "похідна_прогресія": [("алгебра", "Похідна"), ("алгебра", "Прогресії")], "комбінаторика_ймовірність": [("алгебра", "Комбінаторика")],
         "координати_вектори": [("геометрія", "Координати")], "тригонометрія": [("алгебра", "Тригонометричні")],
         "планіметрія_обчислення": [("геометрія", "Трикутники"), ("геометрія", "Чотирикутники"), ("геометрія", "Коло")],
         "рівняння": [("рівняння", "Рівняння"), ("рівняння", "Системи рівнянь")],
         "відп_вирази": [("відп_вирази", "")], "відп_функції": [("відп_функції", "")], "відп_планіметрія": [("відп_планіметрія", "")],
         "кв_функціональне": [("кв_функціональне", "")], "кв_ймовірність_статистика": [("кв_стохастика", "")],
         "кв_стерео": [("кв_стерео", "")], "кв_параметр": [("кв_параметр", "")]}
ТИП_ЗАВДАННЯ = {**{s: "single" for s in list(СЛОТИ)[:15]}, "відп_вирази": "matching", "відп_функції": "matching", "відп_планіметрія": "matching",
                "кв_функціональне": "input", "кв_ймовірність_статистика": "input", "кв_стерео": "input", "кв_параметр": "input"}


def читати(p, default=None):
    if not os.path.exists(p): return default
    return json.load(open(p, encoding="utf-8"))


def типи_каталогів():
    """ключ типу -> опис; кожен тип знає свої слоти"""
    T = {}
    for кат, f in КАТАЛОГИ.items():
        for t in читати(os.path.join(DATA, f + "_нмт.json"), []):
            k = "%s:%s" % (кат, t["код"])
            T[k] = dict(ключ=k, каталог=кат, код=t["код"], група=t["група"], назва=t["назва"], формати=t.get("формати", ""),
                        зразок=dict(latex=t["latex"], відповідь=t["відповідь"], пастки=t.get("пастки", "")),
                        слоти=[s for s, gs in СЛОТИ.items() if any(c == кат and t["група"].startswith(g) for c, g in gs)],
                        роки=collections.Counter(), за_слотами=collections.defaultdict(collections.Counter), теми=collections.Counter(), оригіналів=0)
    return T


def зібрати():
    T = типи_каталогів()
    кат = читати(os.path.join(DATA, "варіант_каталог.json"))
    ген = читати(os.path.join(DATA, "варіант_згенеровані.json"), [])
    клас = читати(os.path.join(DATA, "типи_класифікація.json"), {})
    журнал = читати(os.path.join(ROOT, "варіанти", "журнал.json"), [])
    використано = collections.defaultdict(list)
    for v in журнал:
        for i in v["завдання"]: використано[i].append("варіант %s" % v["номер"])
    for f in sorted(glob.glob(os.path.join(ROOT, "пробні", "*", "склад.json"))):
        s = читати(f)
        for i in s["завдання"]: використано[i].append(s["назва"])
    завдання, без_типу = [], collections.Counter()
    for r in кат:
        тип = клас.get(r["id"])
        if тип in T:
            T[тип]["оригіналів"] += 1
            if r.get("рік"):
                T[тип]["роки"][r["рік"]] += 1
                T[тип]["за_слотами"][r["категорія"]][r["рік"]] += 1
            for u in r.get("теми", []): T[тип]["теми"][u] += 1
        else:
            без_типу[r["категорія"]] += 1
        завдання.append(dict(id=r["id"], джерело="оригінал", слот=r["категорія"], тип=тип if тип in T else None, теми=r.get("теми", []),
                             рік=r.get("рік"), сесія=r.get("сесія_2026"), відповідь=r.get("відповідь"), тип_завдання=r.get("тип"),
                             рисунок=bool(r.get("рисунок")), придатне=bool(r.get("перевірено")) and r.get("дефект", "немає") == "немає"
                             and (r.get("рисунок_огляд") or "ok") != "вада", використано=використано.get(r["id"], [])))
    за_id = {z["id"]: z for z in завдання}
    for g in ген:
        src = за_id.get(g.get("зразок"))
        завдання.append(dict(id=g["id"], джерело="аналог", слот=g["категорія"], тип=src["тип"] if src else None, теми=g.get("теми", []),
                             рік=None, сесія=None, відповідь=g.get("відповідь"), тип_завдання=g.get("тип"), рисунок=bool(g.get("латех_рисунок")),
                             придатне=bool(g.get("перевірено")) and (g.get("рисунок_огляд") or "ok") != "вада", використано=використано.get(g["id"], [])))
    for k, t in T.items():
        for s in t["слоти"]:
            завдання.append(dict(id="зразок:" + k, джерело="зразок каталогу", слот=s, тип=k, теми=sorted(t["теми"], key=lambda u: -t["теми"][u])[:2],
                                 рік=None, сесія=None, відповідь=t["зразок"]["відповідь"], тип_завдання=ТИП_ЗАВДАННЯ[s], рисунок="tikzpicture" in t["зразок"]["latex"],
                                 придатне=True, використано=використано.get("зразок:" + k, [])))
    for f in sorted(glob.glob(os.path.join(ROOT, "пробні", "*", "завдання.json"))):
        for z in читати(f):
            завдання.append(dict(id=z["id"], джерело="авторське пробного", слот=z["слот"], тип=z["тип_каталогу"], теми=z["теми"], рік=None,
                                 сесія=None, відповідь=z["відповідь"], тип_завдання=z["тип"], рисунок=bool(z.get("рисунок")), придатне=True,
                                 використано=використано.get(z["id"], [])))
    типи = {k: dict({kk: v for kk, v in t.items() if kk != "зразок"}, роки=dict(sorted(t["роки"].items())), теми=dict(t["теми"].most_common()),
                    за_слотами={s: dict(sorted(c.items())) for s, c in t["за_слотами"].items()})
            for k, t in T.items()}
    json.dump(dict(типи=типи, завдання=завдання), open(ВИХІД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return типи, завдання, без_типу


if __name__ == "__main__":
    типи, завдання, без_типу = зібрати()
    c = collections.Counter(z["джерело"] for z in завдання)
    print("завдань у базі:", len(завдання), dict(c))
    print("оригінали без типу:", sum(без_типу.values()), dict(без_типу) if без_типу else "")
    for s in СЛОТИ:
        n26 = lambda k: типи[k]["за_слотами"].get(s, {}).get("2026", 0)
        ts = sorted((k for k, t in типи.items() if s in t["слоти"]), key=lambda k: -n26(k))
        print("%-28s %s" % (s, "  ".join("%s:%d" % (k.split(":")[1], n26(k)) for k in ts if n26(k))))
