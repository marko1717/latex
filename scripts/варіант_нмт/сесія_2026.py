def завдання_сесії(сесія):
    бл = {}
    for t in SP.завдання_бази():
        m = re.search(r"%%\s*НМТ 2026, сесія %s, завдання №(\d+)" % re.escape(сесія), t["блок"])
        if m: бл.setdefault(int(m.group(1)), t)
    каталог = {c["id"]: c for c in json.load(open(os.path.join(ROOT, "scripts", "data", "варіант_каталог.json"), encoding="utf-8"))}
    класи = json.load(open(os.path.join(ROOT, "scripts", "data", "типи_класифікація.json"), encoding="utf-8"))
    ор = {t["n"]: t for t in json.load(open(os.path.join(ROOT, "scripts", "data", "originals_2026.json"), encoding="utf-8")) if t["session"] == сесія}
    sys.path.insert(0, os.path.join(ROOT, "scripts", "пробні_нмт"))
    import пробний as П
    T = П.типи_каталогів()
    out = []
    for n in range(1, 23):
        if (сесія, n) in З_ДЖЕРЕЛА:
            д = З_ДЖЕРЕЛА[(сесія, n)]
            блок, відп, id_типу = ор[n]["latex"], д["відповідь"], д["двійник"]
        else:
            t = бл.get(n)
            assert t, "завдання №%d сесії %s немає у файлах тем (додайте до З_ДЖЕРЕЛА)" % (n, сесія)
            к = каталог.get(t["id"], {})
            assert к.get("перевірено") and к.get("дефект") == "немає", ("№%d: відповідь не перевірена або є дефект" % n, к.get("дефект"))
            блок, відп, id_типу = t["блок"], к["відповідь"], t["id"]
        тип = "matching" if "\\matchingGrid" in блок else ("input" if "\\nmtAnswerBox" in блок else "single")
        блок = re.sub(r"(?m)^%[^\n]*\n", "", блок)                                   # службові коментарі джерел
        # блоки бази закінчуються «\par\penalty-20» (бажаний розрив сторінки після завдання) -- переносимо його за сітку,
        # інакше місце для розв'язання відривається від завдання
        блок = re.sub(r"(\\par)?\s*\\penalty-?\d+\s*$", "", блок.strip())
        тип_каталогу = класи.get(id_типу)
        # завдання разом із сіткою -- в одному нерозривному блоці: макроси таблиць відповідей закінчуються \vspace,
        # на якому LaTeX інакше може розірвати сторінку перед сіткою
        out.append(dict(номер=n, тип=тип, latex="\\noindent\\begin{minipage}{\\linewidth}\n" + блок
                        + "\n\\nmtWorkspace{%s}\n\\end{minipage}\n\\par\\vspace{0.35cm}\\penalty-20" % МІСЦЕ[тип], відповідь=відп,
                        розвʼязок=РОЗВʼЯЗКИ.get(сесія, {}).get(n, ""), пастки="",
                        назва_типу=T[тип_каталогу]["назва"] if тип_каталогу in T else ""))
    return out, П


def main(сесія):
    out, П = завдання_сесії(сесія)
    дд, мм = сесія.split(".")
    назва = "НМТ 2026 з математики: варіант за %d %s" % (int(дд), МІСЯЦІ[мм.zfill(2)])
    файл = "НМТ_2026_%s.%s" % (дд.zfill(2), мм.zfill(2))
    К = dict(назва=назва, колонтитул="НМТ 2026, %d %s" % (int(дд), МІСЯЦІ[мм.zfill(2)]), файл=файл,
             вступ=r"Оригінальні завдання основної сесії НМТ 2026 з математики (%d~%s): 15~завдань з вибором однієї відповіді, "
                   r"3~на встановлення відповідності й 4~з короткою відповіддю (максимум 32 бали). Під кожним завданням -- місце "
                   r"для розв'язання; відповіді й розв'язки -- окремим файлом." % (int(дд), МІСЯЦІ[мм.zfill(2)]))
    tex = П.документ(К, out).replace("\\begin{document}", МАКРОС + "\\begin{document}", 1)
    tex_в = П.відповіді(dict(К, назва="НМТ 2026 з математики, варіант за %d %s" % (int(дд), МІСЯЦІ[мм.zfill(2)])), out)
    tex_в = tex_в.replace("\\sectionTitle{Розв'язки й типові помилки}", "\\sectionTitle{Розв'язки}")   # пасток в оригіналів немає
    tex_в = tex_в.replace("\\quad{\\small\\color{gray!80!black}()}", "")                              # тип не визначено
    тека = os.path.join(ROOT, "варіанти")
    texs = {файл: tex, файл + "_відповіді": tex_в}
    for n, t in texs.items():
        open(os.path.join(тека, n + ".tex"), "w", encoding="utf-8").write(t)
    open(os.path.join(тека, файл + "_без_водяного_знака.tex"), "w", encoding="utf-8").write(SP.нфк(
        "%% %s без водяного знака @pvtr2525 -- версія для вчителів.\n\\def\\nmtnowatermark{}\n\\input{%s}\n" % (назва, файл)))
    for n, t in list(texs.items()) + [(файл + "_без_водяного_знака", "\\def\\nmtnowatermark{}\n" + tex)]:
        work = tempfile.mkdtemp()
        компілювати(t, work, "сесія")
        ok, err, pdf, over = компілювати(t, work, "сесія")
        if not ok: raise SystemExit("%s: помилка LaTeX\n%s" % (n, err))
        shutil.copy(pdf, os.path.join(тека, n + ".pdf"))
        print("готово: варіанти/%s.pdf | рядків за полем: %d" % (n, over))
    print("ключ:", " ".join("%d:%s" % (z["номер"], z["відповідь"]) for z in out))


