def тип(b):
    """single / matching / input / ? -- тестові бувають і з переліком \\item чи \\textbf{А}..\\textbf{Д}"""
    k = Z.kind(b)
    if k != "?": return k
    nb = re.sub(r"%[^\n]*", "", b)
    if len(re.findall(r"\\item\b", nb)) >= 5 or len(re.findall(r"\\textbf\{[А-Д]\}", nb)) >= 5: return "single"
    if re.search(r"\\textbf\{А\)?\}", nb) and re.search(r"\\textbf\{Д\)?\}", nb): return "single"   # варіанти в таблиці
    if re.search(r"\\answer[A-Za-z]*\s*\{", nb): return "single"                                  # \\answerListVertical тощо
    if re.search(r"Відповідь:\s*\\fbox", nb): return "input"
    return "?"


def без_відповідей(b):
    """LaTeX завдання без коментарів (там бувають ключі) і без розв'язку -- для розв'язування наосліп"""
    b = re.sub(r"\\ifshowsolutions.*?\\fi\b", "", b, flags=re.S)
    b = re.sub(r"(?<!\\)%[^\n]*", "", b)
    return re.sub(r"\n{3,}", "\n\n", b).strip()


def підпис(b):
    """id завдання: 12 знаків sha1 від тексту без коментарів, рисунків і року (так само нормалізує sig збірників)"""
    return hashlib.sha1(_norm_sig(b).encode("utf-8")).hexdigest()[:12]


def _norm_sig(b):
    t = re.sub(r"%[^\n]*", " ", b)
    t = re.sub(r"(?s)\\begin\{(tikzpicture|axis)\}.*?\\end\{\1\}", " ", t)
    t = re.sub(r"\\nmtyear\{\d+\}|\\(?:begin|end)\{samepage\}", " ", t)
    return re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ]+", "", t)


def файл_теми(k):
    return dict(файли_тем())[k]


def ключ_повтору(b):
    try: return Z.task_key(b)
    except ValueError: return Z.same_key(b)


def рік(b):
    m = re.search(r"\\nmtyear\{(\d{4})\}", b)
    return m.group(1) if m else None


def завдання_бази():
    """усі унікальні завдання бази: список словників {id, теми, файл, тип, рік, блок}"""
    res, seen = [], {}
    for k, f in файли_тем():
        for b in Z.blocks(f):
            key = ключ_повтору(b)
            if key in seen:
                res[seen[key]]["теми"].append(k); continue
            seen[key] = len(res)
            res.append(dict(id=підпис(b), теми=[k], файл=f, тип=тип(b), рік=рік(b), блок=b, ключ=key, старий_id=Z.sig(b)))
    return res


def нфк(s):
    return unicodedata.normalize("NFC", s)


# ---------------------------------------------------------------- відповіді
ЛАТ = str.maketrans({"A": "А", "B": "Б", "V": "В", "G": "Г", "D": "Д"})

def норм_відповідь(a, тип_завдання):
    """єдиний запис відповіді: 'Б' / 'ВБГ' (для 1,2,3) / '422,5'"""
    if a is None: return None
    s = str(a).strip().replace("$", "").replace("{,}", ",").replace("~", " ").replace("\\,", "")
    s = s.replace("−", "-").replace("–", "-").replace("—", "-")
    if тип_завдання == "matching":
        s2 = s.translate(ЛАТ).upper()
        m = re.findall(r"([123])\s*[-–:.)]*\s*-*\s*([АБВГД])", s2)
        if len(m) >= 3:
            d = dict(m)
            if all(x in d for x in "123"): return d["1"] + d["2"] + d["3"]
        m2 = re.fullmatch(r"\s*([АБВГД])\s*([АБВГД])\s*([АБВГД])\s*", s2)
        return "".join(m2.groups()) if m2 else None
    if тип_завдання == "single":
        m = re.fullmatch(r"\s*\(?([АБВГДABVGD])\)?\.?\s*", s.translate(ЛАТ).upper())
        return m.group(1) if m else None
    # число
    s = s.replace(" ", "").replace(".", ",")
    s = re.sub(r"^\+", "", s)
    if not re.fullmatch(r"-?\d+(,\d+)?", s): return None
    if "," in s: s = s.rstrip("0").rstrip(",")
    if s in ("-0",): s = "0"
    return s


def зберегти_json(path, items):
    """список словників -- по рядку на запис (компактно, але diff у git читабельний)"""
    with open(path, "w", encoding="utf-8") as f:
        f.write("[\n")
        for i, r in enumerate(items):
            f.write(json.dumps(r, ensure_ascii=False, separators=(",", ":")) + (",\n" if i < len(items) - 1 else "\n"))
        f.write("]\n")
