def шматок(pts, i, j):
    """частина плавної кривої (ті самі криві Безьє, що й у плавна) від вузла i до вузла j -- для зафарбовування"""
    m = нахили(pts)
    def ч(q): return ("%.3f" % float(q)).rstrip("0").rstrip(".")
    s = ""
    for k in range(i, j):
        (xa, ya), (xb, yb) = pts[k], pts[k + 1]
        h = Fr(xb - xa) / 3
        s += r" .. controls (%s,%s) and (%s,%s) .. (%s,%s)" % (ч(xa + h), ч(ya + m[k] * h), ч(xb - h), ч(yb - m[k + 1] * h), xb, yb)
    return s


