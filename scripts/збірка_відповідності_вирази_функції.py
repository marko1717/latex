def _без_оформлення(x):
    x = re.sub(r"\\(trigStyle|displaystyle|operatorname|mathrm|textit|mbox|text|left|right|dfrac|tfrac|frac|sqrt|par|quad|,|;|!)\b", "", x)
    x = re.sub(r"функці\w*|Функці\w*|координатн\w*|множина|\^\\circ|°", "", x)
    return re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ]+", "", x)


def _пункти(b, мітки):
    return [_без_оформлення(x) for l, x in re.findall(r"\\matchItem\{([^{}]*)\}\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", b) if l in мітки]


def схожість(a, b): return difflib.SequenceMatcher(None, a, b).ratio()


def той_самий(b1, k1, b2, k2):
    """одне завдання в різному оформленні: той самий ключ, схожі пункти 1--3 і варіанти А--Д
    (лише за варіантами чи лише за пунктами не можна: ті самі пункти бувають з іншими варіантами й навпаки)"""
    if not k1 or k1 != k2: return False
    i1, i2 = "".join(_пункти(b1, "1234")), "".join(_пункти(b2, "1234"))
    o1, o2 = "".join(_пункти(b1, L)), "".join(_пункти(b2, L))
    if not (i1 and i2 and o1 and o2):          # пункти таблицею чи рисунками -- за всім текстом
        return схожість(_без_оформлення(SP.без_відповідей(b1)), _без_оформлення(SP.без_відповідей(b2))) >= 0.9
    return схожість(i1, i2) >= 0.75 and схожість(o1, o2) >= 0.75


def _математика(b):
    b = re.sub(r"(?<!\\)%[^\n]*", "", b)
    b = re.sub(r"\\ifshowsolutions.*?\\fi\b", "", b, flags=re.S)
    return re.sub(r"\\begin\{(tikzpicture|axis)\}.*?\\end\{\1\}", " ", b, flags=re.S)


def теми_завдання(b, похідна):
    """що з «пізніх» тем є в завданні: тригонометрія, показникові (змінна в показнику, число e), логарифми, похідна"""
    m, out = _математика(b), []
    if re.search(r"\\(sin|cos|tg|ctg|tan|cot|arcsin|arccos|arctg)(?![A-Za-z])|\\(mathrm|operatorname)\{(tg|ctg)\}|(?<![A-Za-z\\])c?tg(?![A-Za-z])", m):
        out.append("тригонометрія")
    if re.search(r"\\(log|lg|ln)(?![A-Za-z])", m): out.append("логарифми")
    показ = any(re.search(r"[A-Za-z]", re.sub(r"\\[A-Za-z]+", "", e))
                for e in re.findall(r"\^\s*(\{(?:[^{}]|\{[^{}]*\})*\}|\\?[A-Za-z]+|.)", m))
    if показ or re.search(r"(?<![A-Za-z\\])e\s*\\approx|число Ейлера", m): out.append("показникові")
    if похідна and re.search(r"[fygh]'\s*\(|\\prime|похідн|дотичн", m): out.append("похідна")
    return out


def main(режим):
    К = КОНФІГ[режим]
    класи = json.load(open(os.path.join(HERE, "data", "типи_класифікація.json"), encoding="utf-8"))
    каталог = {c["id"]: c for c in json.load(open(os.path.join(HERE, "data", "варіант_каталог.json"), encoding="utf-8"))}
    назви_типів = {t["код"]: t["назва"] for t in json.load(open(os.path.join(HERE, "data", К["типи"]), encoding="utf-8"))}
    блоки = {t["id"]: t for t in SP.завдання_бази()}
    ids = [i for i, тип in класи.items() if тип.startswith(К["категорія"] + ":")]
    добре = lambda i: bool(каталог[i].get("перевірено") and каталог[i].get("дефект") == "немає" and каталог[i].get("відповідь"))
    взято, бачені, повтори, вади = [], {}, collections.Counter(), []
    for i in sorted(ids, key=lambda i: (каталог[i]["рік"], not добре(i), i)):     # версія без вади -- раніше за свій повтор
        b, відп = блоки[i]["блок"], каталог[i].get("відповідь")
        if i in ЯВНІ_ПОВТОРИ:
            assert ЯВНІ_ПОВТОРИ[i][0] in ids, i
            повтори[ЯВНІ_ПОВТОРИ[i][0]] += 1; continue
        двійник = next((j for j, (bj, kj) in бачені.items() if той_самий(bj, kj, b, відп)), None)
        if двійник: повтори[двійник] += 1; continue
        if not добре(i):
            вади.append((i, каталог[i].get("дефект"))); continue
        assert len(відп) in (3, 4) and set(відп) <= set(L), ("немає коректної відповіді", i, відп)   # літера може повторюватися (2024: ВАВ)
        бачені[i] = (b, відп)
        т = теми_завдання(b, К["похідна"])
        взято.append(dict(id=i, тип=класи[i].split(":")[1], рік=каталог[i]["рік"], блок=b, відповідь=відп,
                          файл=блоки[i]["файл"], теми=т, частина=2 if т else 1))
    assert not вади, ("завдання з вадою без повтору -- виправити в базі або внести до таблиці", вади)

    ZT.CFG = dict(src=[("", "11. Трикутники/завдання.tex")], title=К["назва"])
    pre = ZT.preamble()
    теки = sorted({нфк(os.path.dirname(z["файл"])) + "/" for z in взято})
    pre = re.sub(r"\\graphicspath\{.*\}\s*\n", "", pre) + "\\graphicspath{{./}%s}\n" % "".join("{%s}" % t for t in теки)
    out = [pre, "\\begin{document}\n" + ZT.carried_macros() + "\n\\setcounter{zad}{0}\n", "\\chapterTitle{%s}\n" % К["назва"], ""]
    анот = len(out) - 1
    порядок = []
    номер_типу = lambda т: int(т[2:])
    for частина, заголовок in ((1, К["частина1"]), (2, К["частина2"])):
        у_частині = [z for z in взято if z["частина"] == частина]
        if not у_частині: continue
        перший = True
        for тип in sorted({z["тип"] for z in у_частині}, key=номер_типу):
            гр = sorted([z for z in у_частині if z["тип"] == тип], key=lambda z: (z["рік"], z["id"]))
            for k, z in enumerate(гр):
                шапка = ""
                if k == 0:
                    шапка = "\\needspace{0.45\\textheight}"
                    if перший:
                        шапка += "\\sectionTitle{Частина %d. %s}\n" % (частина, заголовок); перший = False
                    назва_типу = re.sub(r"\s*--\s*", " --- ", назви_типів[тип])
                    if len(назва_типу) > 70 and ": " in назва_типу:        # довгу назву -- з нового рядка після двокрапки
                        назва_типу = назва_типу.replace(": ", ":\\\\ ", 1)
                    шапка += "\\typeTitle{%s}\n" % назва_типу
                out.append("\\begin{samepage}\n%s%s\n\\end{samepage}\n" % (шапка, зшити_пункти(z["блок"]).strip()))
                порядок.append(z)
    роки = collections.Counter(z["рік"] for z in порядок)
    n1 = sum(z["частина"] == 1 for z in порядок)
    out[анот] = ("\\noindent{\\small Збірник містить \\textbf{усі %d завдань} НМТ %s--%s років на встановлення відповідності з бази "
                 "(%s). \\textbf{Частина~1} (%d) -- %s, \\textbf{частина~2} (%d) -- решта. Усередині частин завдання згруповано "
                 "за типом; біля кожного вказано рік. Відповіді~--- на останній сторінці.\\par\\vspace{0.15cm}\n"
                 "За роками: %s.}\\par\\vspace{0.45cm}\n") % (
                     len(порядок), min(роки), max(роки), "вирази" if режим == "вирази" else "функції та їхні графіки",
                     n1, К["частина1"][0].lower() + К["частина1"][1:], len(порядок) - n1,
                     ", ".join("\\mbox{%s~--- %d}" % (р, n) for р, n in sorted(роки.items())))
    out.append("\\clearpage\n\\sectionTitle{Відповіді}\n")
    out.append("\\noindent{\\small\\color{gray!80!black}Для кожного завдання -- літери відповідей для пунктів 1, 2, 3. "
               "Відповіді обчислено й звірено з офіційними ключами там, де вони є.}\\par\\vspace{0.3cm}\n")
    for частина in (1, 2):
        номери = [(n, z) for n, z in enumerate(порядок, 1) if z["частина"] == частина]
        if not номери: continue
        out.append("\\noindent\\textbf{Частина %d}\\par\\vspace{0.1cm}\n" % частина)
        out.append("\\begin{multicols}{5}\\noindent\n" + "\\par\n".join("\\mbox{%d~--- %s}" % (n, z["відповідь"]) for n, z in номери)
                   + "\n\\end{multicols}\\par\\vspace{0.2cm}\n")
    out.append("\\end{document}\n")
    файл = К["файл"]
    open(os.path.join(ROOT, файл), "w", encoding="utf-8").write(нфк("\n".join(out)))
    stem = файл[:-4]
    чистий = нфк(stem + "_без_водяного_знака.tex")
    open(os.path.join(ROOT, чистий), "w", encoding="utf-8").write(нфк(
        "%% Збірник «%s» без водяного знака @pvtr2525 -- версія для вчителів.\n"
        "%% Компілюйте цей файл (XeLaTeX); завдання беруться з %s.tex.\n"
        "\\def\\nmtnowatermark{}\n\\input{%s}\n" % (К["назва"], stem, stem)))
    print("записано", файл, "і", чистий)
    print("   оригіналів: %d; узято %d (частина 1 -- %d, частина 2 -- %d); повторів %d" % (
        len(ids), len(порядок), n1, len(порядок) - n1, sum(повтори.values())))
    print("   за роками:", dict(sorted(роки.items())))
    print("   частина 1:", ", ".join("%s(%s)" % (z["id"][:6], z["тип"]) for z in порядок if z["частина"] == 1))
    print("   теми частини 2:", dict(collections.Counter("+".join(z["теми"]) for z in порядок if z["частина"] == 2)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "вирази")
