def ескіз_параболи(s, h, k):
    f = r"%s*1.2*(\x-(%s))*(\x-(%s))+(%s)" % (s, h, h, k)
    r = [r"\begin{tikzpicture}[scale=0.4]",
         r"\draw[->] (-3.3,0) -- (3.5,0) node[%s left, font=\scriptsize] {$x$};" % ("above" if s < 0 else "below"),
         r"\draw[->] (0,-3.3) -- (0,3.5) node[below %s, font=\scriptsize] {$y$};" % ("left" if h > 0 else "right"),
         r"\node[below left, font=\scriptsize] at (0,0) {$0$};",
         r"\begin{scope}\clip (-3.3,-3.3) rectangle (3.3,3.3);",
         r"\draw[very thick, domain=%s:%s, samples=50, smooth] plot (\x, {%s});" % (h - 1.8, h + 1.8, f),
         r"\end{scope}"]
    if h: r.append(r"\draw (%s,0.15) -- (%s,-0.15); \node[%s, font=\scriptsize] at (%s,0) {$%s$};" % (h, h, "above" if s < 0 else "below", h, h))
    if k: r.append(r"\draw (0.15,%s) -- (-0.15,%s); \node[%s, font=\scriptsize] at (0,%s) {$%s$};" % (k, k, "above right" if s < 0 else "below right", k, k))
    r.append(КІНЕЦЬ)
    return "\n".join(r)


