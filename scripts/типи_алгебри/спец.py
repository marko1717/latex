         r"\draw[->] (0,0) -- (26,0) node[right, font=\footnotesize] {$t$, год};",
         r"\draw[->] (0,0) -- (0,%s) node[above, font=\footnotesize] {$T$, $^\circ$C};" % (ymax + 2.5),
