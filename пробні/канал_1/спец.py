# ---------------------------------------------------------------- 5. правильна чотирикутна піраміда: кут між бічною гранню й основою на рисунку
import math as _m5ka
from sympy import Matrix as _Mat5ka

# просторові координати (для перевірки): сторона основи 6, висота 4 -- кут між гранню й основою 53°, інші кути від нього відрізняються
_П5ka = {"A": (0, 0, 0), "B": (6, 0, 0), "C": (6, 6, 0), "D": (0, 6, 0), "O": (3, 3, 0), "S": (3, 3, 4), "M": (6, 3, 0)}
_V5ka = {n: _Mat5ka(p) for n, p in _П5ka.items()}


def _cos_кута5ka(назва):
    """косинус кута XYZ (вершина -- середня літера)"""
    x, y, z = назва
    u, w = _V5ka[x] - _V5ka[y], _V5ka[z] - _V5ka[y]
    return simplify(u.dot(w) / (u.norm() * w.norm()))


def _cos_двогранного5ka():
    """кут між площинами SBC і ABC -- через нормалі"""
    n1 = (_V5ka["B"] - _V5ka["S"]).cross(_V5ka["C"] - _V5ka["S"])
    n2 = (_V5ka["B"] - _V5ka["A"]).cross(_V5ka["D"] - _V5ka["A"])
    return simplify(abs(n1.dot(n2)) / (n1.norm() * n2.norm()))


